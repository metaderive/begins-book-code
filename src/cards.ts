/** 候補が絞れている値（ページ1側） */
export const PAGE1_CANDIDATE_IDS: ReadonlyMap<number, string> = new Map([
  [0x40, "スパルトイ or ランドプロテクト"],
  [0x09, "スパルトイ or ランドプロテクト"],
]);

/** ページを考慮したカード名の解決 */
export function cardName(id: number, page1: boolean): string {
  if (page1) {
    return PAGE1_IDS.get(id) ?? PAGE1_CANDIDATE_IDS.get(id) ?? "?";
  }
  return KNOWN_IDS.get(id) ?? CANDIDATE_IDS.get(id) ?? "?";
}
